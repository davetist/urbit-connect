"""Reproducibly embed the built, same-origin owner assets in the Gall desk."""
import argparse
import hashlib
import json
from pathlib import Path
import stat
import subprocess
import tempfile
from source_safety import read_regular, source_manifest
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true',help='Fail if checked-in assets differ from the current web build')
args=parser.parse_args()
ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'web/dist'
listed=source_manifest(ROOT)
if 'web/index.html' not in listed:raise SystemExit('Owner web source is missing from release manifest')
for name in listed:
    if name.startswith('web/'):
        read_regular(ROOT,name)
def built_assets(folder):
    if not folder.is_dir():raise SystemExit('Run npm --prefix web run build first')
    assets={}
    for path in sorted(folder.rglob('*')):
        mode=path.lstat().st_mode
        if stat.S_ISDIR(mode):continue
        if not stat.S_ISREG(mode):raise SystemExit(f'Unsupported or linked owner asset: {path.name}')
        if path.suffix not in {'.html','.js','.css','.svg'}:raise SystemExit(f'Unsupported bundled asset: {path.name}')
        relative=path.relative_to(folder).as_posix()
        assets[relative]=read_regular(folder,relative)
    if 'index.html' not in assets:raise SystemExit('Run npm --prefix web run build first')
    return assets

assets=built_assets(source)
if args.check:
    with tempfile.TemporaryDirectory(prefix='connect-owner-build-') as folder:
        result=subprocess.run(['npm','--prefix',str(ROOT/'web'),'run','build','--','--outDir',folder],
                              cwd=ROOT,capture_output=True,text=True)
        if result.returncode:raise SystemExit('Could not build current owner source')
        if assets!=built_assets(Path(folder)):
            raise SystemExit('Bundled owner assets are stale; rebuild web and run scripts/bundle_web.py')
entries=[];manifest={}
for relative,raw in sorted(assets.items()):
    mime={'.html':'text/html; charset=utf-8','.js':'text/javascript; charset=utf-8','.css':'text/css; charset=utf-8','.svg':'image/svg+xml'}[Path(relative).suffix]
    if b'\0'in raw:raise SystemExit('NUL in text asset')
    key='/apps/connect/' + relative
    digits=format(int.from_bytes(raw,'little'),'x')
    first=len(digits)%4 or 4
    atom='0x'+'.'.join([digits[:first]]+[digits[i:i+4]for i in range(first,len(digits),4)])
    entries.append(f"      ['{key}' ['{mime}' `@t`{atom}]]")
    manifest[relative]={'sha256':hashlib.sha256(raw).hexdigest(),'bytes':len(raw)}
body=":: Generated by scripts/bundle_web.py from web/dist. Do not edit.\n|%\n++  assets\n  ^-  (map @t [mime=@t body=@t])\n  %-  malt\n  :~\n"+'\n'.join(entries)+'\n  ==\n--\n'
asset=ROOT/'desk/lib/connect-assets.hoon'
record=ROOT/'docs/web-assets.json'
record_text=json.dumps(manifest,indent=2)+'\n'
if args.check:
    if not asset.is_file() or not record.is_file() or asset.read_text()!=body or record.read_text()!=record_text:
        raise SystemExit('Bundled owner assets are stale; rebuild web and run scripts/bundle_web.py')
    print('PASS: bundled owner assets match the current web build')
else:
    asset.write_text(body)
    record.write_text(record_text)
    print(f'Bundled {len(entries)} same-origin assets ({sum(v["bytes"]for v in manifest.values())} bytes)')
