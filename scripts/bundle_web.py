"""Reproducibly embed the built, same-origin owner assets in the Gall desk."""
import hashlib
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'web/dist'
if not (source/'index.html').is_file():raise SystemExit('Run npm --prefix web run build first')
entries=[];manifest={}
for path in sorted(source.rglob('*')):
    if not path.is_file():continue
    if path.suffix not in {'.html','.js','.css','.svg'}:raise SystemExit(f'Unsupported bundled asset: {path.name}')
    mime={'.html':'text/html; charset=utf-8','.js':'text/javascript; charset=utf-8','.css':'text/css; charset=utf-8','.svg':'image/svg+xml'}[path.suffix]
    relative=path.relative_to(source).as_posix();raw=path.read_bytes()
    if b'\0'in raw:raise SystemExit('NUL in text asset')
    key='/apps/connect/' + relative
    digits=format(int.from_bytes(raw,'little'),'x')
    first=len(digits)%4 or 4
    atom='0x'+'.'.join([digits[:first]]+[digits[i:i+4]for i in range(first,len(digits),4)])
    entries.append(f"      ['{key}' ['{mime}' `@t`{atom}]]")
    manifest[relative]={'sha256':hashlib.sha256(raw).hexdigest(),'bytes':len(raw)}
body=":: Generated by scripts/bundle_web.py from web/dist. Do not edit.\n|%\n++  assets\n  ^-  (map @t [mime=@t body=@t])\n  %-  malt\n  :~\n"+'\n'.join(entries)+'\n  ==\n--\n'
(ROOT/'desk/lib/connect-assets.hoon').write_text(body)
(ROOT/'docs/web-assets.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(f'Bundled {len(entries)} same-origin assets ({sum(v["bytes"]for v in manifest.values())} bytes)')
